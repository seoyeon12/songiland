export function getBreed(id: string): Breed {
  const breed = BREEDS.find((entry) => entry.id === id);
  if (!breed) {
    throw new Error(`알 수 없는 견종입니다: ${id}`);
  }
  return breed;
}

export function getCoat(breed: Breed, coatId: string): Coat {
  const coat = breed.coats.find((entry) => entry.id === coatId);
  if (!coat) {
    throw new Error(`${breed.id}에 없는 털색입니다: ${coatId}`);
  }
  return coat;
}

